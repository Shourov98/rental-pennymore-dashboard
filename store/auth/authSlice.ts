import { createAsyncThunk, createSlice, PayloadAction } from "@reduxjs/toolkit";

import { apiClient } from "@/lib/apiClient";
import type { RootState } from "../store";

type LoginRequest = {
  email: string;
  password: string;
};

type ForgotPasswordRequest = {
  email: string;
};

type User = {
  _id: string;
  email: string;
  fullName: string;
  phone: string;
  role: string;
  accountStatus: string;
  emailVerified: boolean;
  lastLoginAt: string;
  referralCode: string;
  referralLink: string;
  totalReferrals: number;
  passwordAutoGenerated: boolean;
  mustChangePassword: boolean;
  createdAt: string;
  updatedAt: string;
};

type LoginResponse = {
  success: boolean;
  message: string;
  data: {
    user: User;
    accessToken: string;
    expiresIn: string;
    mustChangePassword: boolean;
  };
  timestamp: string;
};

type ForgotPasswordResponse = {
  success: boolean;
  message: string;
};

type AuthState = {
  user: User | null;
  accessToken: string | null;
  status: "idle" | "loading" | "succeeded" | "failed";
  error: string | null;
  mustChangePassword: boolean;
  resetEmail: string | null;
  forgotStatus: "idle" | "loading" | "succeeded" | "failed";
  forgotError: string | null;
};

const initialState: AuthState = {
  user: null,
  accessToken: null,
  status: "idle",
  error: null,
  mustChangePassword: false,
  resetEmail: null,
  forgotStatus: "idle",
  forgotError: null,
};

export const login = createAsyncThunk<
  LoginResponse["data"],
  LoginRequest,
  { rejectValue: string }
>("auth/login", async (credentials, { rejectWithValue }) => {
  try {
    const response = await apiClient.post<LoginResponse>(
      "/auth/login",
      credentials,
    );

    return response.data.data;
  } catch (error) {
    if (error instanceof Error) {
      return rejectWithValue(error.message);
    }

    return rejectWithValue("Unable to login. Please try again.");
  }
});

export const forgotPassword = createAsyncThunk<
  { email: string; message: string },
  ForgotPasswordRequest,
  { rejectValue: string }
>("auth/forgotPassword", async ({ email }, { rejectWithValue }) => {
  try {
    const response = await apiClient.post<ForgotPasswordResponse>(
      "/auth/forgot-password",
      { email },
    );

    return { email, message: response.data.message };
  } catch (error) {
    if (error instanceof Error) {
      return rejectWithValue(error.message);
    }

    return rejectWithValue("Unable to send reset code. Please try again.");
  }
});

const authSlice = createSlice({
  name: "auth",
  initialState,
  reducers: {
    logout(state) {
      state.user = null;
      state.accessToken = null;
      state.mustChangePassword = false;
      state.resetEmail = null;
      state.forgotStatus = "idle";
      state.forgotError = null;
    },
    setToken(state, action: PayloadAction<string | null>) {
      state.accessToken = action.payload;
    },
  },
  extraReducers: (builder) => {
    builder
      .addCase(login.pending, (state) => {
        state.status = "loading";
        state.error = null;
      })
      .addCase(login.fulfilled, (state, action) => {
        state.status = "succeeded";
        state.user = action.payload.user;
        state.accessToken = action.payload.accessToken;
        state.mustChangePassword = action.payload.mustChangePassword;
      })
      .addCase(login.rejected, (state, action) => {
        state.status = "failed";
        state.error =
          action.payload ??
          action.error.message ??
          "Login failed. Please try again.";
      })
      .addCase(forgotPassword.pending, (state) => {
        state.forgotStatus = "loading";
        state.forgotError = null;
      })
      .addCase(forgotPassword.fulfilled, (state, action) => {
        state.forgotStatus = "succeeded";
        state.resetEmail = action.payload.email;
      })
      .addCase(forgotPassword.rejected, (state, action) => {
        state.forgotStatus = "failed";
        state.forgotError =
          action.payload ??
          action.error.message ??
          "Failed to send reset code. Please try again.";
      });
  },
});

export const selectAuth = (state: RootState) => state.auth;

export const { logout, setToken } = authSlice.actions;
export default authSlice.reducer;
