type RefreshTokenResponse = {
  success: boolean;
  message: string;
  data: {
    accessToken: string;
    refreshToken?: string;
    expiresIn?: string;
  };
  timestamp: string;
};

export const refreshAccessToken = createAsyncThunk<
  RefreshTokenResponse["data"],
  void,
  { rejectValue: string; state: RootState }
>("auth/refreshAccessToken", async (_, { rejectWithValue, getState }) => {
  try {
    const refreshTokenFromState = getState().auth.refreshToken;
    const refreshTokenFromStorage =
      typeof window !== "undefined"
        ? localStorage.getItem("refreshToken")
        : null;
    const refreshToken = refreshTokenFromState || refreshTokenFromStorage;

    if (!refreshToken) {
      return rejectWithValue("Refresh token is missing.");
    }

    const response = await apiClient.post<RefreshTokenResponse>(
      "/auth/refresh-token",
      { refreshToken }
    );

    if (typeof window !== "undefined") {
      localStorage.setItem("accessToken", response.data.data.accessToken);
      if (response.data.data.refreshToken) {
        localStorage.setItem("refreshToken", response.data.data.refreshToken);
      }
    }

    return response.data.data;
  } catch (error) {
    if (error instanceof Error) {
      return rejectWithValue(error.message);
    }

    return rejectWithValue("Unable to refresh session.");
  }
});

const authSlice = createSlice({
  name: "auth",
  initialState,
  reducers: {
    logout(state) {
      state.user = null;
      state.accessToken = null;
      state.refreshToken = null;
      state.mustChangePassword = false;
      state.resetEmail = null;
      state.forgotStatus = "idle";
      state.forgotError = null;
      state.verifyStatus = "idle";
      state.verifyError = null;
      state.resetOtp = null;
      state.resendStatus = "idle";
      state.resendError = null;
      state.resetStatus = "idle";
      state.resetError = null;
      state.refreshStatus = "idle";
      state.refreshError = null;
      if (typeof window !== "undefined") {
        localStorage.removeItem("accessToken");
        localStorage.removeItem("refreshToken");
        localStorage.removeItem("user");
      }
    },
    setToken(state, action: PayloadAction<string | null>) {
      state.accessToken = action.payload;
    },
    setTokens(
      state,
      action: PayloadAction<{
        accessToken: string | null;
        refreshToken: string | null;
      }>
    ) {
      state.accessToken = action.payload.accessToken;
      state.refreshToken = action.payload.refreshToken;
    },
  },
  extraReducers: (builder) => {
    builder
      .addCase(login.pending, (state) => {
        state.status = "loading";
        state.error = null;
      })
      .addCase(login.fulfilled, (state, action) => {
        state.status = "succeeded";
        state.user = action.payload.user;
        state.accessToken = action.payload.accessToken;
        state.refreshToken = action.payload.refreshToken ?? null;
        state.mustChangePassword = action.payload.mustChangePassword;
      })
      .addCase(login.rejected, (state, action) => {
        state.status = "failed";
        state.error =
          action.payload ??
          action.error.message ??
          "Login failed. Please try again.";
      })
      .addCase(forgotPassword.pending, (state) => {
        state.forgotStatus = "loading";
        state.forgotError = null;
      })
      .addCase(forgotPassword.fulfilled, (state, action) => {
        state.forgotStatus = "succeeded";
        state.resetEmail = action.payload.email;
      })
      .addCase(forgotPassword.rejected, (state, action) => {
        state.forgotStatus = "failed";
        state.forgotError =
          action.payload ??
          action.error.message ??
          "Failed to send reset code. Please try again.";
      })
      .addCase(verifyPasswordOtp.pending, (state) => {
        state.verifyStatus = "loading";
        state.verifyError = null;
      })
      .addCase(verifyPasswordOtp.fulfilled, (state, action) => {
        state.verifyStatus = "succeeded";
        state.resetEmail = action.payload.email;
        state.resetOtp = action.payload.otp;
      })
      .addCase(verifyPasswordOtp.rejected, (state, action) => {
        state.verifyStatus = "failed";
        state.verifyError =
          action.payload ??
          action.error.message ??
          "Verification failed. Please try again.";
      })
      .addCase(resendPasswordOtp.pending, (state) => {
        state.resendStatus = "loading";
        state.resendError = null;
      })
      .addCase(resendPasswordOtp.fulfilled, (state, action) => {
        state.resendStatus = "succeeded";
        state.resetEmail = action.payload.email;
      })
      .addCase(resendPasswordOtp.rejected, (state, action) => {
        state.resendStatus = "failed";
        state.resendError =
          action.payload ??
          action.error.message ??
          "Failed to resend code. Please try again.";
      })
      .addCase(resendVerificationOtp.pending, (state) => {
        state.resendVerificationStatus = "loading";
        state.resendVerificationError = null;
      })
      .addCase(resendVerificationOtp.fulfilled, (state, action) => {
        state.resendVerificationStatus = "succeeded";
        state.resetEmail = action.payload.email;
      })
      .addCase(resendVerificationOtp.rejected, (state, action) => {
        state.resendVerificationStatus = "failed";
        state.resendVerificationError =
          action.payload ??
          action.error.message ??
          "Failed to resend code. Please try again.";
      })
      .addCase(resetPassword.pending, (state) => {
        state.resetStatus = "loading";
        state.resetError = null;
      })
      .addCase(resetPassword.fulfilled, (state) => {
        state.resetStatus = "succeeded";
      })
      .addCase(resetPassword.rejected, (state, action) => {
        state.resetStatus = "failed";
        state.resetError =
          action.payload ??
          action.error.message ??
          "Failed to reset password. Please try again.";
      })
      .addCase(refreshAccessToken.pending, (state) => {
        state.refreshStatus = "loading";
        state.refreshError = null;
      })
      .addCase(refreshAccessToken.fulfilled, (state, action) => {
        state.refreshStatus = "succeeded";
        state.accessToken = action.payload.accessToken;
        state.refreshToken = action.payload.refreshToken ?? state.refreshToken;
      })
      .addCase(refreshAccessToken.rejected, (state, action) => {
        state.refreshStatus = "failed";
        state.refreshError =
          action.payload ??
          action.error.message ??
          "Failed to refresh session.";
      });
  },
});

export const selectAuth = (state: RootState) => state.auth;

export const { logout, setToken, setTokens } = authSlice.actions;
export default authSlice.reducer;
