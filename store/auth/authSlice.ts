type AuthState = {
  user: User | null;
  accessToken: string | null;
  refreshToken: string | null;
  status: "idle" | "loading" | "succeeded" | "failed";
  error: string | null;
  mustChangePassword: boolean;
  resetEmail: string | null;
  forgotStatus: "idle" | "loading" | "succeeded" | "failed";
  forgotError: string | null;
  verifyStatus: "idle" | "loading" | "succeeded" | "failed";
  verifyError: string | null;
  resetOtp: string | null;
  resendStatus: "idle" | "loading" | "succeeded" | "failed";
  resendError: string | null;
  resendVerificationStatus: "idle" | "loading" | "succeeded" | "failed";
  resendVerificationError: string | null;
  resetStatus: "idle" | "loading" | "succeeded" | "failed";
  resetError: string | null;
  refreshStatus: "idle" | "loading" | "succeeded" | "failed";
  refreshError: string | null;
};

const readStoredUser = (): User | null => {
  if (typeof window === "undefined") return null;
  const raw = localStorage.getItem("user");
  if (!raw) return null;
  try {
    return JSON.parse(raw) as User;
  } catch {
    return null;
  }
};

const readStoredToken = (key: "accessToken" | "refreshToken") => {
  if (typeof window === "undefined") return null;
  return localStorage.getItem(key);
};

const initialState: AuthState = {
  user: readStoredUser(),
  accessToken: readStoredToken("accessToken"),
  refreshToken: readStoredToken("refreshToken"),
  status: "idle",
  error: null,
  mustChangePassword: false,
  resetEmail: null,
  forgotStatus: "idle",
  forgotError: null,
  verifyStatus: "idle",
  verifyError: null,
  resetOtp: null,
  resendStatus: "idle",
  resendError: null,
  resendVerificationStatus: "idle",
  resendVerificationError: null,
  resetStatus: "idle",
  resetError: null,
  refreshStatus: "idle",
  refreshError: null,
};

export const login = createAsyncThunk<
  LoginResponse["data"],
  LoginRequest,
  { rejectValue: string }
>("auth/admin/login", async (credentials, { rejectWithValue }) => {
  try {
    const response = await apiClient.post<LoginResponse>(
      "/auth/admin/login",
      credentials
    );

    if (typeof window !== "undefined") {
      localStorage.setItem("accessToken", response.data.data.accessToken);
      if (response.data.data.refreshToken) {
        localStorage.setItem("refreshToken", response.data.data.refreshToken);
      }
      localStorage.setItem("user", JSON.stringify(response.data.data.user));
    }

    return response.data.data;
  } catch (error) {
    if (error instanceof Error) {
      return rejectWithValue(error.message);
    }

    return rejectWithValue("Unable to login. Please try again.");
  }
});

